# Настройки изображения
WIDTH, HEIGHT = 1920, 1080
POINT_RADIUS = 5
ZONE_X1, ZONE_Y1 = 960, 250  
ZONE_X2, ZONE_Y2 = 1130, 890  
# Создаем белое изображение
img = Image.open("picture.png")
draw = ImageDraw.Draw(img)
draw.rectangle((ZONE_X1,ZONE_Y1,ZONE_X2,ZONE_Y2),fill="white",outline='black',width=3)
draw.rectangle((0,0,400,500),fill="white",outline='black',width=3)
# Попытка загрузить шрифт (используем стандартный, если системный недоступен)
try:
    font = ImageFont.truetype("arial.ttf", 18)
except IOError:
    font = ImageFont.load_default()

# Генерация разных цветов для каждого ключа
colors = []
num_keys = len(data)
for i in range(num_keys):
    # Используем HSV для получения ярких и различимых цветов
    hue = i / num_keys
    r, g, b = colorsys.hsv_to_rgb(hue, 0.8, 0.9)
    colors.append((int(r * 255), int(g * 255), int(b * 255)))

# Отрисовка легенды
y_text = 30
for idx, key in enumerate(data.keys()):
    color = colors[idx]
    # Рисуем квадратик цвета
    draw.rectangle([20, y_text, 40, y_text + 20], fill=color, outline='black')
    # Пишем текст ключа
    draw.text((50, y_text), key, fill='black', font=font)
    y_text += 30

# Отрисовка точек
for idx, (key, points) in enumerate(data.items()):
    color = colors[idx]
    for x, y in points:
        # Проверка, чтобы не выйти за границы холста
        if 0 <= x < WIDTH and 0 <= y < HEIGHT:
            # Рисуем закрашенный круг с обводкой (координаты верхнего левого и нижнего правого углов описывающего квадрата)
            draw.ellipse(
                [x - POINT_RADIUS, y - POINT_RADIUS, x + POINT_RADIUS, y + POINT_RADIUS],
                fill=color,
                outline='black'
            )

